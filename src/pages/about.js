// /about — אודות עלון משמעות.
//
// A plain, factual description of what the bulletin is, who writes it, what's
// in each issue and how to get it. Beyond being useful to readers, this is the
// page that answers "what is עלון משמעות?" for search engines and AI assistants:
// it's the one URL that states the essentials in prose, so an engine that can
// only read text (rather than run the SPA) still has something to quote.
// Reached from the footer's "מידע" column — deliberately not from the cover.
//
// Content is static and trusted (no user input), so it's inlined directly,
// reusing the .legal-* chrome from the accessibility/privacy pages.

import { navHtml, footerHtml, bindNav } from '../components/nav.js';
import { loadConfig, loadIndex } from '../lib/store.js';
import { setPageSeo } from '../lib/seo.js';

const CONTACT_EMAIL = 'alon@alonmashmaut.org';

export async function renderAbout() {
  const app = document.getElementById('app');
  const [config, nav, idx] = await Promise.all([loadConfig(), navHtml(), loadIndex().catch(() => null)]);
  // Read the archive's size off the index rather than hard-coding it, so the
  // page still tells the truth a year from now.
  const issues = idx && Array.isArray(idx.weeks) ? idx.weeks.length : 0;
  const scope = issues
    ? `עד היום יצאו <b>${issues}</b> גליונות, וכולם שמורים בארכיון האתר.`
    : 'כל הגליונות שיצאו שמורים בארכיון האתר.';

  app.innerHTML = `
    ${nav}
    <main class="legal-page fade-in">
      <article class="legal">
        <h1 class="legal-title">אודות עלון משמעות</h1>
        <p class="legal-lead"><b>עלון משמעות</b> הוא עלון שבועי של <b>חסידות על פרשת השבוע</b> מתורתו של <b>הרב יצחק גינזבורג שליט״א</b>, המוגש בשפה בהירה ובגובה העיניים. העלון נוסד בתשפ״ה, נכתב ומופץ על ידי תלמידים, ומתפרסם מדי שבוע לקראת שבת — במייל, ברשתות החברתיות ובאתר <a href="/">alonmashmaut.org</a>.</p>

        <h2>מה זה עלון משמעות?</h2>
        <p>בכל שבוע יוצא עלון חדש שנצמד לפרשת השבוע ומוציא ממנה רעיון אחד מרכזי — לא סיכום של הפרשה, אלא מבט חסידי שמברר נקודה אחת לעומק ומחבר אותה לחיים. תורת החסידות עוסקת בפנימיות התורה: לא רק במה שכתוב, אלא במה שהדברים אומרים על הנפש, על העבודה הפנימית ועל היחס שבין האדם לבוראו — וזו הזווית שממנה נכתב כל עלון.</p>
        <p>הרעיון שמנחה את העלון פשוט: <b>חסידות עמוקה לא חייבת להיות סגורה.</b> גם רעיון מופשט אפשר להסביר כך שכל אחד יבין — ובעיקר, שירגיש שהוא מדבר אליו.</p>

        <h2>איך הכל התחיל</h2>
        <p>העלון נוסד בשנת <b>תשפ״ה</b>, מקבוצת בחורים בישיבת <b>״תום ודעת״</b> של הרב יצחק גינזבורג בירושלים. הם חיפשו תוכן קליל ופשוט לחלוקה במבצע תפילין בימי שישי — משהו שאפשר יהיה לתת לכל אדם ברחוב, והוא ייקח ממנו רעיון אחד מאיר לשבת.</p>
        <p>מהדפים שחולקו ברחוב זה התרחב בהדרגה לתפוצה רחבה יותר: רשימת תפוצה במייל, הפצה ברשתות החברתיות, וארכיון מלא כאן באתר.</p>

        <h2>מי עומד מאחורי העלון?</h2>
        <p>התורה שבעלון היא <b>תורתו של הרב יצחק גינזבורג שליט״א</b> — הרעיונות, הדרך והתוכן מבוססים על שיעוריו ומאמריו על פרשת השבוע, ותחתיו מקוטלג התוכן שבאתר.</p>
        <p>העלון עצמו נכתב, נערך ומופץ על ידי <b>תלמידים</b>, מתוך רצון להנגיש את הרעיונות לקהל רחב ובשפה פשוטה.</p>
        <p><b>למי שרוצה דיוק:</b> הדברים נכתבים מתוך דבריו של הרב, אך <b>אינם בהכרח מוגהים על ידו לפני הפרסום</b>. לכן, במקום שבו נדרשת הדייקנות המלאה, יש לפנות למקורות המקוריים של הרב עצמו.</p>

        <h2>למי העלון מיועד?</h2>
        <p>לכל מי שרוצה להיכנס לפרשת השבוע בלי רקע מוקדם, וגם למי שכבר לומד ומחפש זווית נוספת. העלון נכתב כך שיתאים לקריאה בשולחן שבת, בדרך, או בכמה דקות פנויות — כל עלון עומד בפני עצמו, ואפשר להתחיל מכל שבוע.</p>

        <h2>מה יש בכל עלון?</h2>
        <ul>
          <li><b>מאמר מרכזי</b> — רעיון אחד מפרשת השבוע, מבואר לעומק ובבהירות. קריאה של כחמש דקות.</li>
          <li><b>כותרות וחלוקה ברורה</b> — כדי שאפשר יהיה לקרוא ברצף או לדלג לפי עניין.</li>
          <li><b>גרסת PDF להדפסה</b> — בעימוד המקורי של העלון, להורדה או להדפסה לשבת.</li>
          <li><b>גרסת אתר נגישה</b> — הטקסט המלא של העלון זמין גם כדף אינטרנט רגיל.</li>
        </ul>

        <h2>האתר והארכיון</h2>
        <p>באתר שמור <a href="/years">ארכיון מלא</a> של כל העלונים שיצאו, מסודר לפי שנים ולפי סדר קריאת הפרשיות. ${scope} אפשר <a href="/search">לחפש</a> בעלונים לפי פרשה, מילה או נושא, לקרוא כל עלון כדף אינטרנט או לפתוח את קובץ ה-PDF, וגם לפתוח <b>שיחה</b> על עלון ולהגיב לקוראים אחרים.</p>

        <h2>הפצה והדפסה — מותר, ובשמחה</h2>
        <p>העלון נולד כדי להיות מחולק, וכך הוא נשאר: <b>מותר להפיץ ולהדפיס אותו ללא הגבלה</b>. אפשר להדפיס עותקים ולחלק בבית הכנסת, בישיבה, בשולחן שבת או בפעילות בשטח; אפשר להעביר את הקובץ או את הקישור בוואטסאפ, במייל וברשתות החברתיות — הכל בלי צורך בבקשת רשות מראש ובלי תשלום.</p>
        <p>הבקשה היחידה שלנו היא לשמור על העלון כפי שהוא ולציין את המקור — <b>עלון משמעות</b>, <a href="/">alonmashmaut.org</a>.</p>

        <h2>איך מקבלים את העלון?</h2>
        <p>אפשר להירשם לקבלת העלון במייל — בכל ערב שבת נשלח העלון החדש ישירות לתיבה, עם קישור לקריאה באתר ולקובץ להדפסה. ההרשמה חינם, וניתן להסיר את הכתובת מרשימת התפוצה בכל רגע בלחיצה אחת מתוך המייל.</p>

        <h2>תרומות ותמיכה</h2>
        <p>העלון נכתב ומופץ ללא תשלום. מי שמעוניין לתמוך בהמשך ההוצאה וההפצה — או לסייע בדרכים אחרות — מוזמן לפנות אלינו במייל העלון, ונשמח לחזור אליו.</p>

        <h2>יצירת קשר</h2>
        <p>הערות, הארות, תיקונים, בקשות או פנייה בנושא תרומה — נשמח לשמוע:</p>
        <ul class="legal-contact">
          <li><b>דוא״ל:</b> <a href="mailto:${CONTACT_EMAIL}?subject=${encodeURIComponent('פנייה בנושא עלון משמעות')}">${CONTACT_EMAIL}</a></li>
          <li><b>האתר:</b> <a href="/">alonmashmaut.org</a></li>
        </ul>
      </article>
    </main>
    ${footerHtml(config)}
  `;

  bindNav();
  setPageSeo({
    title: 'אודות עלון משמעות — פרשת השבוע מתורת הרב יצחק גינזבורג',
    description: 'עלון משמעות הוא עלון שבועי של חסידות על פרשת השבוע מתורתו של הרב יצחק גינזבורג שליט״א. נוסד בתשפ״ה על ידי בחורים מישיבת ״תום ודעת״ בירושלים, נכתב ומופץ על ידי תלמידים, ומתפרסם מדי שבוע לקראת שבת — עם ארכיון מלא, חיפוש והרשמה במייל.',
    path: '/about',
  });
  window.scrollTo(0, 0);
}
